#!/usr/bin/env python3
"""Build Whisparr 2 at the pinned commit and capture the OpenAPI document its own source produces.

Whisparr 2 serves no spec endpoint. It generates the document at build time from its own
controllers, using Swashbuckle's CLI over the built assembly. The committed
src/Whisparr.Api.V3/openapi.json upstream is regenerated by hand and has three commits in its whole
history, so building the document here rather than reading that file removes the drift instead of
patching around it.

Needs Docker and outbound network: the .NET SDK image is pulled from mcr.microsoft.com and the
pinned commit is fetched from github.com. Neither is vendored here. This is run when a pin moves,
not per change.

    python generator/build_spec.py
"""

import argparse
import getpass
import hashlib
import json
import os
import shutil
import subprocess
import tempfile
from datetime import datetime, timezone

import container
from _common import die, resolve_repo_path, write_bytes_atomic, write_json_lf

SPEC_REPO = "Whisparr/Whisparr"  # measured 2026-09-06
# Recorded in provenance only, and never used to address the source. A ref name moves, and the whole
# point of the pin is that it does not.  measured 2026-09-06
SPEC_REF_NAME = "v2"
SPEC_COMMIT = "face3be8956e4c3798a9364a0f2ea95948e34c1c"  # measured 2026-09-06
SDK_IMAGE_DIGEST = (
    "mcr.microsoft.com/dotnet/sdk@sha256:"
    "c8fdd06e430de9f4ddd066b475ea350d771f341b77dd5ff4c2fafa748e3f2ef2"
)  # measured 2026-09-06
SWASHBUCKLE_VERSION = "6.3.0"  # measured 2026-09-06
SWAGGER_DOC_NAME = "v3"  # measured 2026-09-06
BUILT_ASSEMBLY = "_output/net6.0/linux-x64/Whisparr.dll"  # measured 2026-09-06
CAPTURE_TIMEOUT_SEC = 150  # measured 2026-09-06

DEFAULT_OUT_FILE = "spec/openapi.raw.json"  # measured 2026-09-06
PROVENANCE_PATH = "spec/PROVENANCE.json"  # measured 2026-09-06

HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")

# Inside the container: the checkout, the tool and the bind mount the captures land in.
SOURCE_DIR = "/src"
TOOL_DIR = "/tools"
MOUNT_DIR = "/capture"
CAPTURE_NAMES = ("capture-1.json", "capture-2.json")


def check_tier2(document):
    """The eros discriminator. Path presence only, never openapi or info.version.

    Measured 2026-09-05: both documents declare openapi 3.0.1 and info.version 3.0.0, and both
    declare info.title Whisparr. Path presence is the only thing that separates them.
    """
    paths = document.get("paths") or {}
    required = [p for p in ("/api/v3/series", "/api/v3/episode") if p not in paths]
    forbidden = [p for p in ("/api/v3/movie", "/api/v3/alttitle") if p in paths]

    # One line per condition. A commit that merely dropped an expected path declares no eros path,
    # and a single message covering both would send the reader to the eros branch for a document
    # that is not it.
    problems = []
    if forbidden:
        problems.append(
            "ERROR: REFUSED - this document declares {}. That is the eros branch of "
            "Whisparr/Whisparr, which is Whisparr 3, not Whisparr 2. Nothing was written.".format(
                ", ".join(forbidden)
            )
        )
    if required:
        problems.append(
            "ERROR: REFUSED - the captured document does not declare {}. Nothing was "
            "written.".format(", ".join(required))
        )
    return problems


def container_script():
    """The whole build, as one shell script run inside the pinned SDK container.

    Upstream ships docs.sh at its repository root and this does not call it, for three reasons, each
    of which is a defect in that script rather than a preference here:

      - its Linux and Mac branches assign WHERE where they mean RUNTIME, so the runtime identifier
        never reaches the build and only the Windows branch works;
      - it names whisparr.console.dll, and the assembly the build produces is Whisparr.dll;
      - it backgrounds the capture and kills it after 45 seconds, which is the same problem the
        timeout below solves, handled in a way that hides the capture's own exit status.
    """
    capture_lines = []
    for name in CAPTURE_NAMES:
        # The timeout is load-bearing and not belt and braces. The Swashbuckle CLI boots the full
        # application host, migrates a database and never exits after writing the file, so a run
        # without a kill hangs until the caller gives up. Being killed is therefore the expected
        # end of a successful capture: exit 137 is accepted and every other non-zero status is not.
        capture_lines.append(
            "timeout -s KILL {timeout} {tool}/swagger tofile --output {mount}/{name} "
            "{assembly} {doc} || [ $? -eq 137 ]".format(
                timeout=CAPTURE_TIMEOUT_SEC,
                tool=TOOL_DIR,
                mount=MOUNT_DIR,
                name=name,
                assembly=BUILT_ASSEMBLY,
                doc=SWAGGER_DOC_NAME,
            )
        )

    return "\n".join(
        [
            "set -eu",
            # The one native library the SDK image lacks. Without it the built application cannot
            # open its database and the capture exits before writing anything.
            "apt-get update",
            "apt-get install -y libsqlite3-0",
            "cd " + SOURCE_DIR,
            # The source is addressed by commit and never by branch name, so a branch that moved
            # between the measurement and this run cannot change what is built.
            "git init -q",
            "git remote add origin https://github.com/" + SPEC_REPO + ".git",
            "git fetch --depth 1 origin " + SPEC_COMMIT,
            "git checkout -q FETCH_HEAD",
            "dotnet msbuild -restore src/Whisparr.sln -p:Configuration=Debug -p:Platform=Posix "
            "-p:RuntimeIdentifiers=linux-x64 -t:PublishAllRids",
            "dotnet tool install --version {} --tool-path {} Swashbuckle.AspNetCore.Cli".format(
                SWASHBUCKLE_VERSION, TOOL_DIR
            ),
        ]
        + capture_lines
    )


def read_capture(scratch, name):
    """The bytes of one capture, or None when it is absent or empty."""
    path = os.path.join(scratch, name)
    if not os.path.isfile(path):
        return None
    with open(path, "rb") as handle:
        data = handle.read()
    return data or None


def describe(document):
    """The three counts recorded into provenance, computed from the document rather than stated."""
    paths = document.get("paths") or {}
    operations = 0
    for methods in paths.values():
        if isinstance(methods, dict):
            operations += sum(1 for key in methods if key.lower() in HTTP_METHODS)
    schemas = (document.get("components") or {}).get("schemas") or {}
    return {
        "specPathCount": len(paths),
        "specOperationCount": operations,
        "specSchemaCount": len(schemas),
    }


def build_spec_provenance(body, document):
    """The twelve fields this script owns, in recorded order."""
    observed = describe(document)
    return {
        "builtAt": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "specRepo": SPEC_REPO,
        "specRefName": SPEC_REF_NAME,
        "specCommit": SPEC_COMMIT,
        "specSha256": hashlib.sha256(body).hexdigest(),
        "specBytes": len(body),
        "specOpenApiVersion": document.get("openapi"),
        "specPathCount": observed["specPathCount"],
        "specOperationCount": observed["specOperationCount"],
        "specSchemaCount": observed["specSchemaCount"],
        "sdkImageDigest": SDK_IMAGE_DIGEST,
        "swashbuckleCliVersion": SWASHBUCKLE_VERSION,
    }


def merge_spec_provenance(path, updates):
    """Merge the spec block into a provenance document this script does not create.

    Refuses when the file is absent rather than creating one with a spec block and nothing else,
    which keeps the ordering between the scripts explicit rather than implicit in the file's
    contents.
    """
    if not os.path.exists(path):
        die(
            "ERROR: REFUSED - {} does not exist, and this script merges into it rather than "
            "creating it. Nothing was written.".format(path)
        )

    # A null is not an observation. The comprehension runs over the keys this script owns, before
    # the merge, so a pre-existing key it does not own cannot implicate it.
    unobserved = [
        key
        for key, value in updates.items()
        if value is None or (isinstance(value, str) and not value.strip())
    ]
    if unobserved:
        die(
            "ERROR: REFUSED - provenance would record no observed value for: {}. {} is "
            "untouched.".format(", ".join(unobserved), path)
        )

    with open(path, encoding="utf-8") as handle:
        provenance = json.load(handle)
    # Python dicts preserve insertion order and re-assigning an existing key keeps its position, so
    # a re-run does not reorder the file.
    for key, value in updates.items():
        provenance[key] = value
    # A new capture invalidates the patched spec, and preprocess_spec.py is what puts this back.
    provenance.pop("generatedSpecSha256", None)
    write_json_lf(path, provenance)


def build_parser():
    parser = argparse.ArgumentParser(
        prog="build_spec.py",
        description="Build Whisparr 2 at the pinned commit and capture its OpenAPI document.",
    )
    parser.add_argument("--out-file", default=DEFAULT_OUT_FILE)
    parser.add_argument(
        "--keep-scratch",
        action="store_true",
        help="Leave the host scratch directory in place so a failed run can be inspected.",
    )
    return parser


def main():
    args = build_parser().parse_args()

    out_path = resolve_repo_path(args.out_file)
    default_out = resolve_repo_path(DEFAULT_OUT_FILE)
    provenance_path = resolve_repo_path(PROVENANCE_PATH)

    # The write targets are settled before Docker runs, so a run that could never be allowed to
    # write does not first spend several minutes building.
    # normcase, because on NTFS a differently-cased spelling IS the committed file.
    writing_default = os.path.normcase(out_path) == os.path.normcase(default_out)
    if not writing_default and os.path.normcase(
        os.path.dirname(out_path)
    ) == os.path.normcase(os.path.dirname(default_out)):
        die(
            "ERROR: REFUSED - a non-default output may not be written beside the committed "
            "provenance record. Pass --out-file with a scratch directory. output {} / provenance "
            "{}. Nothing was written.".format(out_path, provenance_path)
        )

    scratch = tempfile.mkdtemp(prefix="whisparr2-build-")
    try:
        # A file the container creates inside the mount inherits the scratch root's ACL, and a root
        # made by tempfile.mkdtemp carries no inheritable entry for the invoking user. Measured on
        # Windows without this grant: the build and both captures succeed, and reading capture-1.json
        # back raises WinError 5, so the run fails after several minutes on a file it just wrote.
        # generate.py carries the same grant for the same reason.
        if os.name == "nt":
            subprocess.run(
                ["icacls", scratch, "/grant", "{}:(OI)(CI)F".format(getpass.getuser())],
                capture_output=True, text=True, check=False,
            )
        # The host path is passed as the platform spells it, which is what generate.py already does.
        # No --user is passed either: this container runs apt-get, so it needs uid 0, and the
        # captures it writes into the mount are world-readable at the default umask.
        mount = scratch + ":" + MOUNT_DIR
        print("Building " + SPEC_REPO + " at " + SPEC_COMMIT + " in " + SDK_IMAGE_DIGEST)
        print("  this pulls an image, fetches source and runs a full build; several minutes")
        result = container.run_docker(
            [
                "run", "--rm",
                "-v", mount,
                "-w", SOURCE_DIR,
                SDK_IMAGE_DIGEST,
                "bash", "-c", container_script(),
            ]
        )
        if result.returncode != 0:
            die(
                "ERROR: REFUSED - the build container exited {}. Nothing was written.".format(
                    result.returncode
                ),
                (result.stdout or "")[-4000:],
                (result.stderr or "")[-4000:],
            )

        captures = []
        for name in CAPTURE_NAMES:
            data = read_capture(scratch, name)
            if data is None:
                die(
                    "ERROR: REFUSED - the capture {} is absent or empty. Nothing was "
                    "written.".format(name),
                    (result.stdout or "")[-4000:],
                )
            captures.append(data)

        first, second = captures
        if first != second:
            # A difference here means the build embeds a timestamp, a path or a hash-ordering
            # artifact, which is silent and expensive to unwind once a client tree is committed on
            # top of it. Both captures came from one built assembly, so nothing else can explain it.
            die(
                "ERROR: REFUSED - the two captures differ. {} is {} bytes, sha256 {}; {} is {} "
                "bytes, sha256 {}. The build is not reproducible. Nothing was written.".format(
                    CAPTURE_NAMES[0],
                    len(first),
                    hashlib.sha256(first).hexdigest(),
                    CAPTURE_NAMES[1],
                    len(second),
                    hashlib.sha256(second).hexdigest(),
                )
            )

        body = first
        try:
            document = json.loads(body)
        except json.JSONDecodeError as error:
            die(
                "ERROR: REFUSED - the captured document is not valid JSON: {}. Nothing was "
                "written.".format(error)
            )

        version = document.get("openapi")
        if not (isinstance(version, str) and version.startswith("3.0.")):
            die(
                "ERROR: REFUSED - the captured document declares openapi {!r}, expected a 3.0.x "
                "document. Nothing was written.".format(version)
            )

        problems = check_tier2(document)
        if problems:
            die(*problems)

        out_dir = os.path.dirname(out_path)
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)
        write_bytes_atomic(out_path, body)

        print("  + {} bytes".format(len(body)))
        print("  + sha256 " + hashlib.sha256(body).hexdigest())
        print("Done. " + out_path)

        # The provenance record describes the committed deliverable, so a scratch run never
        # touches it.
        if writing_default:
            merge_spec_provenance(provenance_path, build_spec_provenance(body, document))
            print("Recorded. " + provenance_path)
    finally:
        if args.keep_scratch:
            print("Scratch kept at " + scratch)
        else:
            shutil.rmtree(scratch, ignore_errors=True)


if __name__ == "__main__":
    main()
